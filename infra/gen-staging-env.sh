#!/usr/bin/env bash
# Generates the local-only staging secrets for infra/docker-compose.staging.yml.
# Output (gateway.env / web.env) is gitignored and must never be committed or
# copied into production: staging is a single-machine stack bound to 127.0.0.1.
set -euo pipefail
cd "$(dirname "$0")"

if [[ -e gateway.env || -e web.env ]]; then
  echo "gateway.env or web.env already exists; remove both to regenerate" >&2
  exit 1
fi

umask 077

rand_b64() { # $1 = byte length; single-line base64 (no trailing newline)
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 "$1" | tr -d '\n'
  else
    head -c "$1" /dev/urandom | base64 | tr -d '\n'
  fi
}

rand_hex() { # $1 = byte length; 2x hex chars
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1"
  else
    head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

# AES-256-GCM: parseEncryptionKey() requires exactly 32 decoded bytes.
POOL_KEY_ENCRYPTION_KEY="$(rand_b64 32)"
# HMAC pepper for virtual-key hashes: must share the same value in both services.
KEY_HASH_PEPPER="$(rand_b64 32)"
GATEWAY_INTERNAL_TOKEN="$(rand_hex 32)"
AUTH_SECRET="$(rand_b64 48)"
MOCK_BILLING_WEBHOOK_SECRET="$(rand_hex 24)"
# Ed25519 PKCS#8 (DER, base64) for per-item marketplace signatures.
MANIFEST_SIGNING_KEY="$(openssl genpkey -algorithm ED25519 -outform DER | base64 | tr -d '\n')"

cat > gateway.env <<EOF
# Generated by infra/gen-staging-env.sh — local staging only. Never commit.
POOL_KEY_ENCRYPTION_KEY=${POOL_KEY_ENCRYPTION_KEY}
KEY_HASH_PEPPER=${KEY_HASH_PEPPER}
GATEWAY_INTERNAL_TOKEN=${GATEWAY_INTERNAL_TOKEN}
EOF

cat > web.env <<EOF
# Generated by infra/gen-staging-env.sh — local staging only. Never commit.
POOL_KEY_ENCRYPTION_KEY=${POOL_KEY_ENCRYPTION_KEY}
KEY_HASH_PEPPER=${KEY_HASH_PEPPER}
GATEWAY_INTERNAL_TOKEN=${GATEWAY_INTERNAL_TOKEN}
AUTH_SECRET=${AUTH_SECRET}
MOCK_BILLING_WEBHOOK_SECRET=${MOCK_BILLING_WEBHOOK_SECRET}
MANIFEST_SIGNING_KEY=${MANIFEST_SIGNING_KEY}
EOF

chmod 600 gateway.env web.env
echo "wrote infra/gateway.env and infra/web.env (mode 600, gitignored)"
